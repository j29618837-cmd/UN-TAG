  const getLang = () => {
    const stored = localStorage.getItem(LANG_KEY);
    return stored === "en" || stored === "zh-Hant" ? stored : DEFAULT_LANG;
  };

  const t = (key, lang = getLang()) => (messages[lang] && messages[lang][key]) || messages[DEFAULT_LANG][key] || key;

  const renderSwitchers = () => {
    document.querySelectorAll("[data-language-switcher]").forEach((mount) => {
      if (mount.dataset.ready === "true") return;
      mount.dataset.ready = "true";
      mount.innerHTML =
        '<div class="inline-flex items-center gap-1 rounded-full border border-orange-200 bg-white/80 p-1 text-xs font-semibold text-[#564336] shadow-sm backdrop-blur">' +
        '<button type="button" data-lang-button="zh-Hant" class="rounded-full px-3 py-1 transition-colors"></button>' +
        '<button type="button" data-lang-button="en" class="rounded-full px-3 py-1 transition-colors"></button>' +
        "</div>";
    });

    document.querySelectorAll("[data-lang-button]").forEach((button) => {
      if (button.dataset.bound === "true") return;
      button.dataset.bound = "true";
      button.addEventListener("click", () => {
        localStorage.setItem(LANG_KEY, button.dataset.langButton);
        applyTranslations();
      });
    });
  };

  const applyTranslations = () => {
    const lang = getLang();
    document.documentElement.lang = lang;
    if (document.body.dataset.pageTitle) document.title = t(document.body.dataset.pageTitle, lang);

    renderSwitchers();

    document.querySelectorAll("[data-lang-button]").forEach((button) => {
      button.textContent = t(button.dataset.langButton === "en" ? "lang.en" : "lang.zh", lang);
      const active = button.dataset.langButton === lang;
      button.classList.toggle("bg-[#964900]", active);
      button.classList.toggle("text-white", active);
    });

    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n, lang);
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder, lang));
    });

    document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel, lang));
    });
  };

